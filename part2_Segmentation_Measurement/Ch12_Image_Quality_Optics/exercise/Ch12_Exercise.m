%[text] $$f_{50} = \sqrt{\frac{\ln 2}{2\pi^2\sigma^2}}$$
%[text] **把它反過來用**：量到 MTF50，就能推回等效的高斯 σ。
%[text] **要求**：
%[text] 1. 推導反算式 $\sigma = f(f_{50})$
%[text] 2. 用 `ch12_makeSlantedEdge` 產生數個**已知** σ 的斜邊
%[text] 3. 對每一張量 MTF50，再反推 σ，與真實值比較
%[text] 4. 畫出「真實 σ vs 反推 σ」，並標出 y=x 參考線
%[text] 5. **在哪個範圍內反推是可信的？** 用主教材第 8.1 節的
%[text]    有效區間（MTF50 約 0.05–0.25 cycles/pixel）檢查你的結果 \
