%[text] # 加分題：量測不確定度
%[text] 一個工程報告不只要給數字，還要給**不確定度**。
%[text] **要求**：
%[text] 1. 對同一批硬幣，用三種前處理（不同的門檻、不同的形態學參數）
%[text]    各做一次量測
%[text] 2. 比較三次結果的差異——這是**方法不確定度**
%[text] 3. 對單一次量測，算出十枚硬幣的標準差——這是**樣本變異**
%[text] 4. 兩者哪個大？你的報告該報哪一個？ \
%[text] **提示**：如果方法不確定度比樣本變異還大，
%[text] 那麼你報告的「標準差」其實反映的是**你的處理流程不穩定**，
%[text] 而不是物件真的大小不一。這是很常見也很嚴重的誤導。

