%[text] # 練習 2：量化 Poisson 混合的顏色偏移
%[text] 主教材說 Poisson 混合「物件顏色會被背景拉走」，
%[text] 並用內部保真 PSNR 19.5 dB 作為證據。
%[text] **但 PSNR 沒有告訴你偏移的方向。** 這題要量出來。
%[text] **要求**：
%[text] 1. 取一個前景物件，準備**至少 4 個亮度明顯不同的背景**
%[text]    （提示：`bg * k` 或 `bg + c` 就能造出來）
%[text] 2. 對每個背景做一次 Poisson 混合與一次 Guided 混合
%[text] 3. 量測**遮罩內部**（記得內縮）的平均 RGB，與原始前景比較
%[text] 4. 畫出「背景亮度 vs 物件平均亮度偏移」
%[text] 5. 回答三個問題：
%[text]    - 偏移是**隨機**還是**系統性**的？
%[text]    - 偏移量與背景亮度有關嗎？是什麼關係？
%[text]    - Guided 混合有同樣的問題嗎？ \
%[text] **為什麼這題重要**：如果偏移是系統性的，
%[text] 那用 Poisson 合成的訓練資料就會讓模型學到
%[text] 「物件顏色 = f(背景亮度)」這個**真實世界不存在的相關性**。

