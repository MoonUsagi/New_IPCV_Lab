%[text] # 練習 3：驗證「擴增後標註還對不對」
%[text] 這是資料集出錯最常見的原因，而且**錯了不會報錯**。
%[text] **要求**：
%[text] 1. 取一個物件與它的遮罩，算出邊界框（用 `ch13_maskToBox`）
%[text] 2. 用 `randomAffine2d` 產生一個隨機變換（要含旋轉）
%[text] 3. **用兩種方式**得到變換後的邊界框：
%[text]    - **方式 A（錯的）**：只變換影像，邊界框沿用原來的
%[text]    - **方式 B（對的）**：變換遮罩，再從變換後的遮罩重算邊界框
%[text] 4. 把兩個框都畫在變換後的影像上，並計算兩者的 IoU
%[text] 5. 重複 20 次不同的隨機變換，統計 IoU 的分布
%[text] 6. 回答：旋轉角度越大，兩者的差距越大嗎？ \
%[text] **然後**：
%[text] 7. 用 `insertObjectInImage` 搭配 `GeometricAugmentation` 做同一件事，
%[text]    確認它回傳的框是**方式 B**（正確的那個）
%[text] **這題的意義**：自己做擴增很容易忘記同步更新標註。
%[text] `insertObjectInImage` 把擴增放在插入**之前**，所以框天生就是對的——
%[text] 這是用它而不是自己寫的主要理由。

