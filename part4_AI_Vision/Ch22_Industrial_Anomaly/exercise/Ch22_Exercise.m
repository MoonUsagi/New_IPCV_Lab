%[text] # 練習 3：良品要幾張才夠
%[text] 主教材用 24 張。**這題要找出實際需要多少。**
%[text] **要求**：
%[text] 1. 把良品訓練集從 4 張掃到 64 張
%[text] 2. 每個數量都重新訓練並算分離度
