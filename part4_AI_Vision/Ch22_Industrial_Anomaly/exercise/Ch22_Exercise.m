%[text] # 練習 4：把門檻決策變成成本計算
%[text] 主教材 §5 說「門檻由成本決定」，但沒有算過。
%[text] **這題要你把它變成一個真正的決策。**
%[text] **要求**：
%[text] 1. 定義兩個成本（用你自己的估計並說明依據）：
%[text]    - `c_overkill`：一次過殺的成本（人工複檢）
%[text]    - `c_escape`：一次漏檢的成本（流到客戶端）
%[text] 2. 對每個門檻算**期望總成本**（要考慮瑕疵率！）
%[text] 3. 找出成本最低的門檻
%[text] 4. 把瑕疵率從 0.1% 掃到 10%，看最佳門檻怎麼移動
%[text] 5. 回答：**瑕疵率對最佳門檻的影響有多大？** \
%[text] **第 2 點的關鍵是瑕疵率。** 產線的瑕疵率通常低於 1%，
%[text] 所以即使漏檢的單次成本很高，**過殺的總量可能還是更貴**——
%[text] 因為良品的數量是瑕疵的一百倍。
%[text] 這和第 20 章的類別不平衡是同一件事，只是換到成本上。

