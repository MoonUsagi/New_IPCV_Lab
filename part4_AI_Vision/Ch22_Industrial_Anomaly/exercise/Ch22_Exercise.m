%[text] # 練習 2：良品訓練集被汙染會怎樣
%[text] 主教材 §10 說「訓練集混進一張瑕疵品，模型會把那種瑕疵當成正常，
%[text] **而且不會報錯**」。**這題要你量出那個代價。**
%[text] **要求**：
%[text] 1. 在良品訓練集裡**刻意混入** 1、2、4、8 張瑕疵品
%[text] 2. 每次都重新訓練並評估
%[text] 3. 畫出「汙染數量 vs 瑕疵的平均分數」
%[text] 4. 找出**汙染幾張就會讓方法失效**
%[text] 5. 設計一個**能事先偵測汙染**的檢查 \
%[text] **第 5 點是實務上真正需要的東西。**
%[text] 提示：先用全部良品訓練一次，然後看**訓練集自己**的分數分布——
%[text] 被汙染的那幾張會不會有異常的分數？
