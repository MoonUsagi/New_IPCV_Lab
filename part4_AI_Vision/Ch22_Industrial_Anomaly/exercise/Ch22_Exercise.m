%[text] # 練習 1：把瑕疵變難，直到方法失效
%[text] 主教材的合成瑕疵太明顯（間隔 609 個標準差）。
%[text] **這題要你找出 PatchCore 的失效點。**
%[text] **要求**：
%[text] 1. 修改瑕疵的**對比度**（暗斑與背景的亮度差），從明顯掃到幾乎看不見
%[text] 2. 每個對比度都重新評估：良品與瑕疵的分數分布、分離度
%[text] 3. 畫出「對比度 vs 分離度」
%[text] 4. 找出**分布開始重疊**的對比度
%[text] 5. 再掃**瑕疵大小**（從大到只有幾個像素），做同一件事
%[text] 6. 回答：對比度與大小，哪一個對 PatchCore 比較致命？ \
%[text] **第 6 點的提示**：PatchCore 比較的是**特徵**而不是像素。
%[text] 特徵是經過下採樣的，所以很小的瑕疵可能在特徵圖上消失
%[text] （第 19 章練習 5 的同一個問題）。

