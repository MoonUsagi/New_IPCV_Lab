%[text] # 練習 2：把骨幹比較做對
%[text] 主教材 §6 的骨幹排名**站不住**（§6.1 證明了）。
%[text] **這題要你用正確的方法重做一次。**
%[text] **要求**：
%[text] 1. 對每個骨幹重複 **5 個不同的隨機切分**，記錄每次的準確率
%[text] 2. 報告每個骨幹的**平均 ± 標準差**
%[text] 3. 用**配對比較**（每個切分上比較兩個骨幹）而不是各自的平均值
%[text]    ——想想為什麼配對比較更有力
%[text] 4. 回答：現在能不能分辨這四個骨幹了？若還不能，還需要什麼？
%[text] 5. 估算：要可靠分辨 2 個百分點的差異，總共需要多少次評估？ \
%[text] **第 3 點是統計上的關鍵。** 同一個切分上兩個骨幹面對
%[text] **完全一樣的測試影像**，所以切分造成的變異在配對差值裡會抵消掉。
%[text] 這和「兩組獨立樣本比較平均值」的檢定力差很多。

