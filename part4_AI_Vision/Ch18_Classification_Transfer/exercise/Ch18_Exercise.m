%[text] # 練習 1：領域距離決定遷移效果
%[text] 主教材 §4 說「ImageNet 特徵在手寫數字上只到 85% 左右，
%[text] 因為兩個領域差很遠」。**這題要你驗證這個解釋。**
%[text] **要求**：
%[text] 1. 建一個**和 ImageNet 比較接近**的分類任務。
%[text]    用 `vision/visiondata` 裡的自然照片：
%[text]    `vehicles`（295 張車輛）與 `stopSignImages`（41 張停止標誌）。
%[text]    取每類 41 張做成平衡的二分類任務。
%[text] 2. 用同一個骨幹、同一層、同樣的流程做特徵抽取 + SVM
%[text] 3. 比較「自然照片二分類」與「手寫數字十分類」的準確率
%[text] 4. **加上 §6.1 的雜訊分析**：差異大得過雜訊嗎？
%[text] 5. 回答：這個結果支持還是反駁「領域距離決定遷移效果」？ \
%[text] **第 5 點要小心，這一題的陷阱在公平性。**
%[text] 車 vs 標誌只有兩類，隨機猜就有 50%；
%[text] 手寫數字有十類，隨機猜只有 10%。
%[text] **直接比準確率是不公平的。** 至少要做兩件事：
%[text] - 用**超越隨機的幅度**來比：$(acc - chance)/(1 - chance)$
%[text] - 或者把數字也**限制成兩類**，讓隨機基準一致
%[text] 兩種都做，看結論會不會一樣。

