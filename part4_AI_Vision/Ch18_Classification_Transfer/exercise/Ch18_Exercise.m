%[text] # 練習 6：特徵可視化——為什麼深層比較好
%[text] 主教材 §5 量到「越深越好（20% → 85%）」，但沒有**看到**原因。
%[text] **這題要你把特徵空間畫出來。**
%[text] **要求**：
%[text] 1. 對 `res2b_relu`（最差）與 `pool5`（最好）各抽一次特徵
%[text] 2. 用 `tsne` 或 `pca` 降到 2 維
%[text] 3. 用類別上色，畫兩張散布圖並排
%[text] 4. 量化「分得開不開」：算每個類別的**類內距離／類間距離**比值
